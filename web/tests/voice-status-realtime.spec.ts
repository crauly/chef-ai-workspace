import {test,expect,type WebSocketRoute} from "@playwright/test";
test.skip(!process.env.NEXT_PUBLIC_DEMO_WS_URL,"Run with NEXT_PUBLIC_DEMO_WS_URL=ws://localhost:3100 (mock socket only)");
test("realtime partial is display-only, completion is canonical, and stopped audio drains visibly",async({page})=>{
 let socket:WebSocketRoute|undefined,parses=0,saves=0;
 await page.route("**/api/voice-ticket",route=>route.fulfill({json:{ticket:"fixture-single-use-ticket"}}));
 await page.route("**/api/voice-recipe",route=>{parses++;return route.fulfill({json:{title:"パスタ",materials:[{name:"ディチェコ",quantity:"100",unit:"g",supplier:"",price_jpy:"",price_quantity:"",price_unit:""}],selling_price_jpy:"",notes:[],missing:[]}});});
 await page.route("**/api/recipes/full",route=>{saves++;return route.abort();});
 await page.routeWebSocket("**/demo/voice-realtime",ws=>{socket=ws;ws.onMessage(message=>{if(typeof message==="string"&&message.includes("ticket"))ws.send(JSON.stringify({type:"ready"}));});});
 await page.goto("/");
 await page.evaluate(()=>{Object.defineProperty(navigator.mediaDevices,"getUserMedia",{value:async()=>{const c=new AudioContext();return c.createMediaStreamDestination().stream;}});});
 await page.getByRole("button",{name:"🎙 音声操作を開始",exact:true}).click();
 await expect.poll(()=>Boolean(socket)).toBe(true);
 await expect(page.locator('.voice-status-list [data-stage="listen"]')).toBeVisible();
 const send=(event:Record<string,unknown>)=>socket!.send(JSON.stringify(event));
 send({type:"speechStart",turnId:"one"});send({type:"transcript",transcript:"でぃちぇこ",final:false});
 await expect(page.getByLabel("認識した発話",{exact:true})).toContainText("でぃちぇこ");
 expect(parses).toBe(0);expect(saves).toBe(0);await expect(page.getByLabel("未保存のレシピ下書き")).toHaveCount(0);
 send({type:"transcript",transcript:"でぃちぇこ100g",final:true});
 await expect(page.getByLabel("認識した発話",{exact:true})).toContainText("でぃちぇこ100g");expect(parses).toBe(0);
 await page.getByRole("button",{name:"■ マイクを停止",exact:true}).click();
 await expect(page.locator('.voice-status-list [data-stage="transcribe"]')).toBeVisible();
 await expect(page.locator('.voice-status-list [data-stage="listen"]')).toHaveCount(0);
 send({type:"speechComplete",turnId:"one",transcript:"ディチェコ100g"});
 send({type:"speechComplete",turnId:"one",transcript:"duplicate"});
 socket!.close();
 await expect(page.getByLabel("未保存のレシピ下書き")).toContainText("ディチェコ");
 await expect(page.getByLabel("認識した発話",{exact:true})).toHaveText("ディチェコ100g");
 await expect(page.locator(".voice-status-list")).toHaveCount(0);expect(parses).toBe(1);expect(saves).toBe(0);
});
